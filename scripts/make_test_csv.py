"""Генерирует CSV, имитирующий экспорт из Яндекс.Форм."""
import csv
from pathlib import Path

HEADERS = [
    "Отметка времени",
    "ФИО",
    "Класс",
    "[task_001] Сколько будет 1010₂ + 110₂?",
    "[task_002] Переведите 255 в 16-ю СС",
    "[task_003] Сколько будет 12₈ + 7₈?",
    "[task_004] Что выведет for i in range(3): print(i)",
    "[task_005] Сколько раз выполнится for i in range(1,10,2)?",
]

# Иванов — сильный; Петров — средний; Сидорова — слабая
ROWS = [
    ["2026-09-20 10:15:00", "Иванов Ваня", "10А", "16", "FF", "21", "0 1 2", "5"],
    ["2026-09-20 10:15:00", "Петров Петя", "10А", "16", "FE", "21", "0 1 2", "4"],
    ["2026-09-20 10:15:00", "Сидорова Маша", "10А", "14", "FF", "", "0 1", ""],
    ["2026-09-20 10:15:00", "Кузнецов Лёша", "10А", "16", "FF", "21", "0 1 2", "5"],
    ["2026-09-20 10:15:00", "Морозова Даша", "10А", "16", "FF", "19", "0 1 2", "5"],
]

out = Path(__file__).parent.parent / "data" / "test_responses.csv"
out.parent.mkdir(exist_ok=True)

with open(out, "w", encoding="utf-8-sig", newline="") as f:
    writer = csv.writer(f)
    writer.writerow(HEADERS)
    writer.writerows(ROWS)

print(f"Written: {out}")